export function drawWeapon(wid: TWeapon, ctx: CanvasRenderingContext2D, cellSize: Size, player: { pos: Point, theta: number }, color: string) {
    const weapon = drawFns[wid];
    if (weapon?.draw) {
        weapon.draw(ctx, cellSize, player, color);
    } else {
        drawUnknown(ctx, cellSize, player, color);
    }
}

export function drawWeaponProj(wid: TWeapon, ctx: CanvasRenderingContext2D, pos: Point, vel: Point, radius: number, color: string) {
    const weapon = drawFns[wid];
    if (weapon?.drawProj) {
        weapon.drawProj(ctx, pos, vel, radius, color);
    } else {
        drawProjUnknown(ctx, pos, vel, radius, color);
    }
}

export function drawWeaponIcon(wid: TWeapon, ctx: CanvasRenderingContext2D, rect: Rect, colors: [string, string]) {
    const weapon = drawFns[wid];
    if (weapon?.drawIcon) {
        weapon.drawIcon(ctx, rect, colors);
    } else {
        drawIconUnknown(ctx, rect, colors);
    }
}

function drawUnknown(ctx: CanvasRenderingContext2D, cellSize: Size, player: { pos: Point, theta: number }, color: string) {
    const spx = player.pos.x;
    const spy = player.pos.y;

    const stickLen = cellSize.h;
    const epx = spx + stickLen * Math.cos(player.theta);
    const epy = spy + stickLen * Math.sin(player.theta);

    ctx.fillStyle = color;
    ctx.font = `${cellSize.h}px`;
    ctx.fillText("?", epx, epy);
}

function drawIconUnknown(ctx: CanvasRenderingContext2D, { x, y, w, h }: Rect, [color1, color2]: [string, string]) {
    ctx.save();

    ctx.translate(x, y);
    ctx.strokeStyle = color2;
    ctx.beginPath();
    ctx.roundRect(0, 0, w, h, w * 0.1);
    ctx.stroke();

    ctx.restore();

    ctx.save();

    ctx.fillStyle = color1;
    ctx.font = `${h * 2}px`;
    ctx.textAlign = "center";
    ctx.textBaseline = "middle";
    ctx.fillText("?", x + w / 2, y + h / 2);

    ctx.restore();
}

function drawProjUnknown(ctx: CanvasRenderingContext2D, pos: Point, _vel: Point, radius: number, color: string) {
    ctx.save();

    ctx.beginPath();
    ctx.arc(pos.x, pos.y, radius, 0, 2 * Math.PI);
    ctx.fillStyle = color;
    ctx.fill();

    ctx.restore();
}
